def convert_run(
    results: List[Dict],
    out_dir: str,
    scenario: str,
    instance: str,
    optimizer: str,
    seed: int,
    cs_json: Dict,
    negate_costs: bool = True,
    deepcave_version: str = "1.3",
) -> None:
    major_minor = tuple(int(x) for x in deepcave_version.split(".")[:2])
    include_cpu_time = major_minor >= (1, 4)

    run_name = f"{optimizer}_{scenario}_{instance}_seed{seed}"
    run_dir = os.path.join(out_dir, run_name)
    os.makedirs(run_dir, exist_ok=True)

    # ------------------------------------------------------------------ 1. configspace.json
    with open(os.path.join(run_dir, "configspace.json"), "w") as f:
        json.dump(cs_json, f, indent=2)

    # ------------------------------------------------------------------ 2. configs.json + origins.json
    # Only keep HPs that are in the ConfigSpace (drop fidelity params, etc.)
    cs_hp_names = {hp["name"] for hp in cs_json.get("hyperparameters", [])}

    configs: Dict[str, Dict] = {}
    origins: Dict[str, None] = {}
    config_to_id: Dict[str, int] = {}

    for r in results:
        raw = _config_dict(r["config"])
        # Keep only HP names present in the ConfigSpace
        filtered = {k: v for k, v in raw.items() if k in cs_hp_names}
        # Align types to CS declarations
        cfg = _align_config_to_cs(filtered, cs_json)
        key = _config_key(cfg)
        if key not in config_to_id:
            cid = len(config_to_id)
            config_to_id[key] = cid
            configs[str(cid)] = cfg
            origins[str(cid)] = None

    with open(os.path.join(run_dir, "configs.json"), "w") as f:
        json.dump(configs, f, indent=2)
    with open(os.path.join(run_dir, "origins.json"), "w") as f:
        json.dump(origins, f, indent=2)

    # ------------------------------------------------------------------ 3. history.jsonl
    budgets_seen: List[float] = []
    costs_seen: List[float] = []
    history_lines: List[str] = []

    for i, r in enumerate(results):
        raw = _config_dict(r["config"])
        filtered = {k: v for k, v in raw.items() if k in cs_hp_names}
        cfg = _align_config_to_cs(filtered, cs_json)
        config_id = config_to_id[_config_key(cfg)]

        budget = float(r["eval_budget"])
        cost = -float(r["result"]) if negate_costs else float(r["result"])

        costs_seen.append(cost)
        if budget not in budgets_seen:
            budgets_seen.append(budget)

        if include_cpu_time:
            trial = [config_id, budget, int(seed), [cost], 0.0,
                     float(i), float(i + 1), STATUS_SUCCESS, {}]
        else:
            trial = [config_id, budget, int(seed), [cost],
                     float(i), float(i + 1), STATUS_SUCCESS, {}]

        history_lines.append(json.dumps(trial))

    with open(os.path.join(run_dir, "history.jsonl"), "w") as f:
        f.write("\n".join(history_lines) + "\n")

    # ------------------------------------------------------------------ 4. meta.json
    budgets_seen.sort()
    objective = {
        "name": "1 - accuracy" if negate_costs else "accuracy",
        "lower": float(min(costs_seen)) if costs_seen else 0.0,
        "upper": float(max(costs_seen)) if costs_seen else 1.0,
        "lock_lower": False,
        "lock_upper": False,
        "optimize": "lower" if negate_costs else "upper",
    }
    meta = {
        "objectives": [objective],
        "budgets": budgets_seen,
        "seeds": [int(seed)],
    }
    with open(os.path.join(run_dir, "meta.json"), "w") as f:
        json.dump(meta, f, indent=2)


