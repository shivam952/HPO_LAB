def _serialize_hp(hp) -> Dict:
    """
    Manually serialize a single hyperparameter to the ConfigSpace JSON format
    (format_version 0.4) that DeepCAVE / ConfigSpace 1.x can read back.
    Works with ConfigSpace 0.6.x which has no built-in JSON writer.
    """
    from ConfigSpace.hyperparameters import (
        UniformFloatHyperparameter,
        UniformIntegerHyperparameter,
        CategoricalHyperparameter,
        OrdinalHyperparameter,
        Constant,
        NormalFloatHyperparameter,
        NormalIntegerHyperparameter,
    )

    if isinstance(hp, UniformFloatHyperparameter):
        return {
            "type": "uniform_float",
            "name": hp.name,
            "lower": float(hp.lower),
            "upper": float(hp.upper),
            "default_value": float(hp.default_value),
            "log": bool(hp.log),
            "meta": None,
        }
    elif isinstance(hp, UniformIntegerHyperparameter):
        return {
            "type": "uniform_int",
            "name": hp.name,
            "lower": int(hp.lower),
            "upper": int(hp.upper),
            "default_value": int(hp.default_value),
            "log": bool(hp.log),
            "meta": None,
        }
    elif isinstance(hp, CategoricalHyperparameter):
        choices = [str(c) for c in hp.choices]
        default = str(hp.default_value)
        if default not in choices:
            default = choices[0]
        return {
            "type": "categorical",
            "name": hp.name,
            "choices": choices,
            "weights": None,
            "default_value": default,
            "meta": None,
        }
    elif isinstance(hp, OrdinalHyperparameter):
        seq = [str(s) for s in hp.sequence]
        return {
            "type": "ordinal",
            "name": hp.name,
            "sequence": seq,
            "default_value": str(hp.default_value),
            "meta": None,
        }
    elif isinstance(hp, Constant):
        return {
            "type": "constant",
            "name": hp.name,
            "value": hp.value,
            "meta": None,
        }
    elif isinstance(hp, NormalFloatHyperparameter):
        return {
            "type": "normal_float",
            "name": hp.name,
            "mu": float(hp.mu),
            "sigma": float(hp.sigma),
            "default_value": float(hp.default_value),
            "log": bool(hp.log),
            "lower": float(hp.lower) if hp.lower is not None else None,
            "upper": float(hp.upper) if hp.upper is not None else None,
            "meta": None,
        }
    elif isinstance(hp, NormalIntegerHyperparameter):
        return {
            "type": "normal_int",
            "name": hp.name,
            "mu": float(hp.mu),
            "sigma": float(hp.sigma),
            "default_value": int(hp.default_value),
            "log": bool(hp.log),
            "lower": int(hp.lower) if hp.lower is not None else None,
            "upper": int(hp.upper) if hp.upper is not None else None,
            "meta": None,
        }
    else:
        raise ValueError(f"Unsupported hyperparameter type: {type(hp)}")


def _serialize_condition(cond) -> Dict:
    """Serialize a condition to ConfigSpace JSON format 0.4."""
    from ConfigSpace.conditions import (
        EqualsCondition, NotEqualsCondition,
        LessThanCondition, GreaterThanCondition,
        InCondition, AndConjunction, OrConjunction,
    )

    if isinstance(cond, AndConjunction):
        return {
            "type": "AND",
            "child": cond.child.name,
            "conditions": [_serialize_condition(c) for c in cond.components],
        }
    elif isinstance(cond, OrConjunction):
        return {
            "type": "OR",
            "child": cond.child.name,
            "conditions": [_serialize_condition(c) for c in cond.components],
        }
    elif isinstance(cond, EqualsCondition):
        return {
            "type": "EQ",
            "child": cond.child.name,
            "parent": cond.parent.name,
            "value": str(cond.value) if isinstance(cond.value, str) else cond.value,
        }
    elif isinstance(cond, NotEqualsCondition):
        return {
            "type": "NEQ",
            "child": cond.child.name,
            "parent": cond.parent.name,
            "value": str(cond.value) if isinstance(cond.value, str) else cond.value,
        }
    elif isinstance(cond, LessThanCondition):
        return {
            "type": "LT",
            "child": cond.child.name,
            "parent": cond.parent.name,
            "value": cond.value,
        }
    elif isinstance(cond, GreaterThanCondition):
        return {
            "type": "GT",
            "child": cond.child.name,
            "parent": cond.parent.name,
            "value": cond.value,
        }
    elif isinstance(cond, InCondition):
        return {
            "type": "IN",
            "child": cond.child.name,
            "parent": cond.parent.name,
            "values": list(cond.values),
        }
    else:
        raise ValueError(f"Unsupported condition type: {type(cond)}")


def cs_to_json_dict(cs) -> Dict:
    """
    Convert a ConfigSpace 0.6.x ConfigurationSpace object to a JSON-compatible
    dict in format_version 0.4 (readable by ConfigSpace 1.x and DeepCAVE 1.4.1).
    """
    hyperparameters = [_serialize_hp(hp) for hp in cs.get_hyperparameters()]
    conditions = [_serialize_condition(c) for c in cs.get_conditions()]
    # Forbiddens — skip for now (not used in YAHPO benchmarks)
    return {
        "name": cs.name if hasattr(cs, "name") else None,
        "hyperparameters": hyperparameters,
        "conditions": conditions,
        "forbiddens": [],
        "python_module_version": "1.2.0",
        "format_version": 0.4,
    }


def get_yahpo_configspace_json(scenario: str, instance: str, yahpo_data_path: str) -> Dict:
    """
    Load the ConfigSpace for a YAHPO Gym benchmark and return it as a dict
    ready to be written to configspace.json.

    Uses drop_fidelity_params=True so the fidelity HP (epoch / trainsize)
    is excluded — matching what was optimised.

    Compatible with ConfigSpace 0.6.x (manual serialization) and 1.x+ (to_json).
    """
    from yahpo_gym import BenchmarkSet, local_config

    local_config.init_config()
    local_config.set_data_path("/Users/ssg/.yahpo_data")

    bench = BenchmarkSet(scenario)
    bench.set_instance(instance)
    cs = bench.get_opt_space(drop_fidelity_params=True)

    # ConfigSpace 1.x+
    if hasattr(cs, "to_json"):
        with tempfile.NamedTemporaryFile(suffix=".json", mode="w", delete=False) as f:
            tmp_path = f.name
        try:
            cs.to_json(tmp_path)
            with open(tmp_path) as f:
                return json.load(f)
        finally:
            os.unlink(tmp_path)

    # ConfigSpace 0.6.x — manual serialization
    return cs_to_json_dict(cs)


