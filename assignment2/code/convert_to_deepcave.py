def _normalise_value(val):
    """Convert numpy scalars to plain Python types."""
    if isinstance(val, (bool, np.bool_)):
        return str(val)
    if isinstance(val, np.integer):
        return int(val)
    if isinstance(val, np.floating):
        return float(val)
    return val


def _config_dict(config: Dict) -> Dict:
    return {k: _normalise_value(v) for k, v in config.items()}


def _config_key(cfg: Dict) -> str:
    return json.dumps(cfg, sort_keys=True)


# ---------------------------------------------------------------------------
# Align config values to ConfigSpace types
# ---------------------------------------------------------------------------

def _align_config_to_cs(config: Dict, cs_json: Dict) -> Dict:
    """
    Cast each config value to the type declared in the ConfigSpace JSON.
    This prevents type mismatches when DeepCAVE reconstructs Configuration objects.

    - uniform_float  → float
    - uniform_int    → int
    - categorical    → str  (ConfigSpace stores categorical values as strings)
    """
    hp_types = {}
    for hp in cs_json.get("hyperparameters", []):
        hp_types[hp["name"]] = hp["type"]

    aligned = {}
    for k, v in config.items():
        t = hp_types.get(k)
        if t == "uniform_float":
            aligned[k] = float(v)
        elif t == "uniform_int":
            aligned[k] = int(round(float(v)))
        elif t == "categorical":
            aligned[k] = str(v)
        else:
            # HP not in CS (e.g. fidelity param stored in config by mistake) — skip
            aligned[k] = _normalise_value(v)
    return aligned


