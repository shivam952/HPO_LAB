"""
Convert custom HPO .pkl results to the DeepCAVE native format.
WARNING! This script was generated by an AI!

Key difference from previous version:
  configspace.json is taken directly from YAHPO Gym (via BenchmarkSet),
  NOT inferred from observed values. This is critical for benchmarks like
  nb301 which have conditional hyperparameters — inferring from data loses
  all conditions and causes ActiveHyperparameterNotSetError in DeepCAVE.

Supports DeepCAVE v1.3  (8-field Trial, no cpu_time)
     and DeepCAVE v1.4+ (9-field Trial, with cpu_time).

Trial array layout:
  v1.3  → [config_id, budget, seed, costs, start_time, end_time, status, additional]
  v1.4+ → [config_id, budget, seed, costs, cpu_time, start_time, end_time, status, additional]

DeepCAVE minimises costs → we store -accuracy with optimize="lower".
Pass --no-negate to store raw accuracy with optimize="upper".
"""

import json
import os
import pickle
import tempfile
from pathlib import Path
from typing import Dict, List, Optional, Tuple

import numpy as np

STATUS_SUCCESS = 1

KNOWN_SCENARIOS = [
    "rbv2_xgboost", "rbv2_svm", "rbv2_glmnet", "rbv2_ranger",
    "nb301", "lcbench",
]
KNOWN_OPTIMIZERS = [
    "BOHB_Round", "BOHB_Bracket",
    "RandomSearch", "BayesianOptimisation", "GridSearch",
    "SuccessiveHalving", "Hyperband",
]

# Maps scenario → (instance, fidelity_param)
# Needed to initialise BenchmarkSet and drop fidelity from ConfigSpace
SCENARIO_META = {
    "nb301":        {"fidelity": "epoch"},
    "rbv2_xgboost": {"fidelity": "trainsize"},
    "rbv2_svm":     {"fidelity": "trainsize"},
    "rbv2_glmnet":  {"fidelity": "trainsize"},
    "rbv2_ranger":  {"fidelity": "trainsize"},
    "lcbench":      {"fidelity": "epoch"},
}


# ---------------------------------------------------------------------------
# YAHPO ConfigSpace loader
