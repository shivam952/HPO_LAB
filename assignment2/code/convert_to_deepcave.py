def parse_pkl_filename(filename: str) -> Tuple[str, str, str, int]:
    stem = filename.replace(".pkl", "")
    parts = stem.split("_")

    seed_token = parts[-1]
    if not seed_token.startswith("seed"):
        raise ValueError(f"Last token '{seed_token}' is not 'seed<N>'")
    seed = int(seed_token[4:])
    remaining = "_".join(parts[:-1])

    optimizer = None
    for opt in sorted(KNOWN_OPTIMIZERS, key=len, reverse=True):
        if remaining.startswith(opt + "_"):
            optimizer = opt
            remaining = remaining[len(opt) + 1:]
            break
    if optimizer is None:
        raise ValueError(f"Cannot identify optimizer in '{filename}'")

    scenario = None
    for sc in sorted(KNOWN_SCENARIOS, key=len, reverse=True):
        if remaining.startswith(sc + "_"):
            scenario = sc
            remaining = remaining[len(sc) + 1:]
            break
    if scenario is None:
        raise ValueError(f"Cannot identify scenario in '{filename}' (after optimizer='{optimizer}')")

    return optimizer, scenario, remaining, seed  # remaining = instance


# ---------------------------------------------------------------------------
# Batch conversion
# ---------------------------------------------------------------------------

def load_pkl(path: str) -> List[Dict]:
    with open(path, "rb") as f:
        return pickle.load(f)


def convert_all(
    in_dir: str,
    out_dir: str,
    yahpo_data_path: str,
    negate_costs: bool = True,
    deepcave_version: str = "1.3",
) -> None:
    os.makedirs(out_dir, exist_ok=True)

    # Cache ConfigSpaces so we don't reload YAHPO for every seed
    cs_cache: Dict[Tuple[str, str], Dict] = {}
    errors = []

    for root, _, files in os.walk(in_dir):
        for fname in sorted(files):
            if not fname.endswith(".pkl"):
                continue

            path = os.path.join(root, fname)
            try:
                optimizer, scenario, instance, seed = parse_pkl_filename(fname)
            except ValueError as e:
                print(f"  [SKIP] {fname}: {e}")
                errors.append((fname, str(e)))
                continue

            # Load ConfigSpace from YAHPO (cached)
            cs_key = (scenario, instance)
            if cs_key not in cs_cache:
                try:
                    print(f"  Loading ConfigSpace for {scenario}/{instance} from YAHPO...", end="", flush=True)
                    cs_cache[cs_key] = get_yahpo_configspace_json(scenario, instance, yahpo_data_path)
                    print(" OK")
                except Exception as e:
                    print(f" FAILED: {e}")
                    errors.append((fname, f"ConfigSpace load failed: {e}"))
                    continue

            try:
                results = load_pkl(path)
                convert_run(
                    results, out_dir,
                    scenario, instance, optimizer, seed,
                    cs_json=cs_cache[cs_key],
                    negate_costs=negate_costs,
                    deepcave_version=deepcave_version,
                )
                run_name = f"{optimizer}_{scenario}_{instance}_seed{seed}"
                print(f"  OK   {fname}  →  {run_name}/")
            except Exception as e:
                import traceback
                print(f"  [ERR] {fname}: {e}")
                traceback.print_exc()
                errors.append((fname, str(e)))

    print(f"\nDone. {len(errors)} error(s).")
    for fname, msg in errors:
        print(f"  • {fname}: {msg}")


